export function attachFeatureIdsToBehavioralChecks(commandName, behavioralChecks = []) {
  const commandMap = COMMAND_FEATURE_MAP[commandName] || {};
  return behavioralChecks.map(check => {
    const featureIds = commandMap[check?.name];
    return featureIds?.length ? { ...check, featureIds: [...featureIds] } : { ...check };
  });
}

export function getCommandFeatureMap() {
  return COMMAND_FEATURE_MAP;
}
